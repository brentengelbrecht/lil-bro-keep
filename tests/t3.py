from playwright.sync_api import sync_playwright
def ok(c,m): print(('PASS ' if c else 'FAIL ')+m)
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1000,'height':800})
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(700)
    pg.evaluate("""()=>{const x=blank();x.title='Zed';x.body='hello';x.color=0;x.ts=Date.now()+1000;notes.unshift(x);save();render()}""")
    pg.wait_for_timeout(300)
    cid=pg.evaluate("notes.find(n=>n.title==='Zed').id"); C=f'.card[data-id="{cid}"]'
    first=pg.evaluate("s=>document.querySelector(s+' .acts .ib').dataset.act",C)
    ok(first=='colpick',f"palette is the first icon in the row ({first})")
    pg.hover(C); pg.wait_for_timeout(350); pg.click(C+' [data-act=colpick]')
    ok(pg.locator('.cpop .sw').count()==12,"popover shows 12 swatches")
    ok(pg.locator('.ov').count()==0,"note was not opened")
    pg.click('.cpop .sw >> nth=7'); pg.wait_for_timeout(200)
    col=pg.evaluate("[notes.find(n=>n.id==='%s').color,getComputedStyle(document.querySelector('%s')).backgroundColor,getComputedStyle(document.documentElement).getPropertyValue('--k7')]"%(cid,C))
    ok(col[0]==7,f"colour changed to Sky blue (bg {col[1]}, var {col[2].strip()})")
    ok(pg.locator('.cpop .sw.on').count()==1 and pg.evaluate("document.querySelector('.cpop .sw.on').dataset.i")=='7',"selected swatch marked, popover stays open")
    pg.click('.cpop .sw >> nth=2'); pg.wait_for_timeout(150)
    ok(pg.evaluate("notes.find(n=>n.id==='%s').color"%cid)==2,"can change again")
    pg.keyboard.press('Escape'); ok(pg.locator('.cpop').count()==0,"Escape closes popover")
    pg.hover(C); pg.wait_for_timeout(350); pg.click(C+' [data-act=colpick]'); pg.mouse.click(900,700); pg.wait_for_timeout(450)
    ok(pg.locator('.cpop').count()==0 and pg.locator('.ov').count()==0,"outside click closes without opening a note")
    pg.hover(C); pg.wait_for_timeout(350); pg.click(C+' [data-act=colpick]'); pg.click(C+' [data-act=colpick]',force=True)
    ok(pg.locator('.cpop').count()==0,"clicking the icon again toggles it off")
    pg.hover(C); pg.wait_for_timeout(350); pg.click(C+' [data-act=colpick]'); pg.hover(C); pg.wait_for_timeout(350); pg.click(C+' [data-act=lblpick]',force=True)
    ok(pg.locator('.cpop .lq').count()==1 and pg.locator('.cpop .sw').count()==0,"switching to label picker replaces the colour picker")
    pg.keyboard.press('Escape')
    pg.reload(); pg.wait_for_timeout(700)
    ok(pg.evaluate("notes.find(n=>n.title==='Zed').color")==2,"colour persists after reload")
    ok(pg.evaluate("getComputedStyle(document.querySelector('.card[data-id=\"%s\"]')).backgroundColor"%cid)!='rgba(0, 0, 0, 0)',"card shows background")
    pg.hover(C); pg.wait_for_timeout(350); pg.click(C+' [data-act=colpick]'); pg.screenshot(path='shot_pal.png',clip={'x':250,'y':100,'width':750,'height':450})
    print('errors',errs); b.close()
